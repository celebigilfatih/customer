// Function to search cities
export const searchCities = (query: string): string[] => {
  if (!query) return TURKISH_CITIES;
  
  const normalizedQuery = query.toLowerCase().replace(/ı/g, 'i').replace(/ğ/g, 'g').replace(/ü/g, 'u').replace(/ş/g, 's').replace(/ö/g, 'o').replace(/ç/g, 'c');
  
  return TURKISH_CITIES.filter(city => {
    const normalizedCity = city.toLowerCase().replace(/ı/g, 'i').replace(/ğ/g, 'g').replace(/ü/g, 'u').replace(/ş/g, 's').replace(/ö/g, 'o').replace(/ç/g, 'c');
    return normalizedCity.includes(normalizedQuery);
  });
};